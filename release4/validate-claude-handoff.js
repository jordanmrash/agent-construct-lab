'use strict';
const fs=require('fs'),path=require('path');
const ROOT=process.env.COWORK_ROOT||path.resolve(__dirname,'..','..');
const DIR=path.join(ROOT,'AgentConstructLab','release4');
const handoff=fs.readFileSync(path.join(DIR,'claude-certification-handoff.md'),'utf8');
const suite=JSON.parse(fs.readFileSync(path.join(DIR,'claude-certification-suite.json'),'utf8'));
const checks=[];const add=(id,ok)=>checks.push({id,status:ok?'pass':'fail'});
add('construct',handoff.includes('certified-workspace-agent'));
add('output-root',handoff.includes('Outputs/2026-09-29 - Release 4 Claude Certification/'));
for(const t of suite.tests)add('test:'+t.id,handoff.includes(t.id));
add('no-history-shortcut',handoff.includes('Do not use historical conversation text'));
add('no-m365-shortcut',handoff.includes('Microsoft 365 execution evidence'));
add('no-could-not-run-promotion',handoff.includes('Do not mark `could_not_run` as `pass`'));
add('scoring-command',handoff.includes('score-platform-evidence.js'));
add('certification-guard',handoff.includes('certified: true'));
const failed=checks.filter(x=>x.status==='fail');
const OUT=path.join(ROOT,'Outputs','2026-09-29 - Release 4 Claude Certification Handoff');fs.mkdirSync(OUT,{recursive:true});
fs.writeFileSync(path.join(OUT,'claude-certification-handoff-validation.json'),JSON.stringify({schema_version:'1.0.0',generated_at:new Date().toISOString(),checks,overall:failed.length?'fail':'pass'},null,2)+'\n');
console.log('R4_CLAUDE_HANDOFF_CHECKS='+checks.length);console.log('R4_CLAUDE_HANDOFF_FAILED='+failed.length);console.log('R4_CLAUDE_HANDOFF_RESULT='+(failed.length?'FAIL':'PASS'));process.exit(failed.length?1:0);
