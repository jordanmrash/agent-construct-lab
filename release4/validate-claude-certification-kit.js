'use strict';
const fs=require('fs'),path=require('path');
const ROOT=process.env.COWORK_ROOT||path.resolve(__dirname,'..','..');
const DIR=path.join(ROOT,'AgentConstructLab','release4');
const suite=JSON.parse(fs.readFileSync(path.join(DIR,'claude-certification-suite.json'),'utf8'));
const pending=JSON.parse(fs.readFileSync(path.join(DIR,'claude-platform-evidence.pending.json'),'utf8'));
const matrix=JSON.parse(fs.readFileSync(path.join(DIR,'behavioral-equivalence-matrix.json'),'utf8'));
const checks=[];const add=(id,ok,d)=>checks.push({id,status:ok?'pass':'fail',detail:ok?undefined:d});
const suiteCriteria=new Set(suite.tests.flatMap(t=>t.criteria));const matrixCriteria=new Set(matrix.criteria.map(c=>c.id));
add('suite-target',suite.target==='claude','wrong target');
add('suite-test-count',suite.tests.length===9,'expected 9');
add('suite-covers-matrix',matrix.criteria.every(c=>suiteCriteria.has(c.id)),'missing criterion');
add('pending-count',pending.results.length===10,'expected 10');
add('pending-unique',new Set(pending.results.map(r=>r.criterion_id)).size===10,'duplicates');
add('pending-covers-matrix',pending.results.every(r=>matrixCriteria.has(r.criterion_id))&&matrix.criteria.every(c=>pending.results.some(r=>r.criterion_id===c.id)),'coverage mismatch');
add('pending-not-certified',pending.results.every(r=>r.status==='could_not_run'),'premature pass');
add('forbidden-shortcuts',suite.forbidden_shortcuts.length===4,'expected 4');
const failed=checks.filter(x=>x.status==='fail');
const out={schema_version:'1.0.0',generated_at:new Date().toISOString(),checks,overall:failed.length?'fail':'pass'};
const od=path.join(ROOT,'Outputs','2026-09-29 - Release 4 Claude Certification Kit');fs.mkdirSync(od,{recursive:true});fs.writeFileSync(path.join(od,'claude-certification-kit-validation.json'),JSON.stringify(out,null,2)+'\n');
console.log('R4_CLAUDE_KIT_TESTS='+suite.tests.length);console.log('R4_CLAUDE_KIT_CRITERIA='+suiteCriteria.size);console.log('R4_CLAUDE_KIT_CHECKS='+checks.length);console.log('R4_CLAUDE_KIT_FAILED='+failed.length);console.log('R4_CLAUDE_KIT_RESULT='+(failed.length?'FAIL':'PASS'));process.exit(failed.length?1:0);
